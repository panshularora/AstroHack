type Ctx = {
  locale: Locale
  setLocale: (l: Locale) => void
  t: (key: Msg, vars?: Vars) => string
}

const I18nContext = createContext<Ctx | null>(null)

function readLocale(): Locale {
  try {
    const saved = localStorage.getItem(KEY)
    if (saved === "hi" || saved === "en") return saved
  } catch {
    /* ignore */
  }
  return "en"
}

function writeLocale(l: Locale) {
  try {
    localStorage.setItem(KEY, l)
  } catch {
    /* ignore */
  }
  if (typeof document !== "undefined") {
    document.documentElement.lang = l === "hi" ? "hi" : "en"
    document.documentElement.dataset.locale = l
  }
}

let current: Locale = "en"
const listeners = new Set<(l: Locale) => void>()

function applyLocale(l: Locale) {
  if (l !== "en" && l !== "hi") return
  current = l
  writeLocale(l)
  listeners.forEach((fn) => fn(l))
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const l = typeof window !== "undefined" ? readLocale() : "en"
    current = l
    writeLocale(l)
    return l
  })

  useEffect(() => {
    const on = (l: Locale) => setLocaleState(l)
    listeners.add(on)
    const onStorage = (e: StorageEvent) => {
      if (e.key === KEY && (e.newValue === "hi" || e.newValue === "en")) applyLocale(e.newValue)
    }
    window.addEventListener("storage", onStorage)
    return () => {
      listeners.delete(on)
      window.removeEventListener("storage", onStorage)
    }
  }, [])

  const value = useMemo<Ctx>(
    () => ({
      locale,
      setLocale: applyLocale,
      t: (key, vars) => fill(dict[locale][key] || dict.en[key], vars),
    }),
    [locale]
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (ctx) return ctx
  return {
    locale: current,
    setLocale: applyLocale,
    t: (key: Msg, vars?: Vars) => fill(dict[current][key] || dict.en[key], vars),
  }
}
